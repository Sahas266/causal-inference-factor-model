"""Tests for the Gaussian HMM regime classifier.

Uses synthetic 2-regime data generated by hand so we can verify the classifier
identifies the regimes correctly and labels them deterministically.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

pytest.importorskip("hmmlearn", reason="hmmlearn not installed")

from causal_portfolio.regimes.hmm import (
    RegimeClassifier,
    build_regime_features,
    dwell_stats,
)


def _synthetic_two_regime_features(n=600, seed=0) -> np.ndarray:
    """Two regimes: first half low-stress, second half high-stress."""
    rng = np.random.default_rng(seed)
    half = n // 2
    low = rng.normal(loc=[0.0, 0.0], scale=[0.3, 0.3], size=(half, 2))
    high = rng.normal(loc=[2.0, 2.0], scale=[0.5, 0.5], size=(n - half, 2))
    return np.vstack([low, high])


# ── deterministic state labeling ────────────────────────────────────


def test_state_zero_is_lower_stress():
    """The relabel step must always put the lower-mean state at index 0."""
    X = _synthetic_two_regime_features()
    cls = RegimeClassifier(n_states=2, random_state=42).fit(X)
    means = cls.state_means()
    # Feature 0 mean of state 0 must be < state 1
    assert means[0, 0] < means[1, 0]


def test_labels_match_regime_structure():
    X = _synthetic_two_regime_features(n=600)
    cls = RegimeClassifier(n_states=2, random_state=42).fit(X)
    labels = cls.decode(X)
    # First half should be mostly label 0 (low stress)
    assert (labels[:300] == 0).mean() > 0.85
    # Second half should be mostly label 1 (high stress)
    assert (labels[300:] == 1).mean() > 0.85


def test_decode_returns_correct_shape():
    X = _synthetic_two_regime_features(n=300)
    cls = RegimeClassifier(n_states=2, random_state=42).fit(X)
    labels = cls.decode(X)
    assert labels.shape == (300,)
    assert set(np.unique(labels).tolist()).issubset({0, 1})


# ── causal decode ───────────────────────────────────────────────────


def test_causal_decode_does_not_use_future():
    """predict_causal at t=k should only depend on data[:k+1]."""
    X = _synthetic_two_regime_features(n=200)
    cls = RegimeClassifier(n_states=2, random_state=42).fit(X)
    labels_full = cls.predict_causal(X)

    # Recompute by truncating: labels_full[t] should equal predict_causal(X[:t+1])[-1]
    for t in [10, 50, 100, 150]:
        truncated = cls.predict_causal(X[: t + 1])
        assert labels_full[t] == truncated[-1]


